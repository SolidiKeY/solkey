    /// parses the Solidity file found at the provided [URI] and converts it into a
    /// list of [SyntaxElement]s of declarations representing the Solidity programs
    /// @param file the URI where to find the Solidity code
    /// @return list of top level declarations (usually contracts) representing the Solidity code
    public List<SyntaxElement> parse(URI file) throws IOException {
        ObjectMapper mapper = new ObjectMapper();

        JsonNode root = mapper.readTree(file.toURL().openStream());
        return json2SolidityAST(root);
    }

    public List<SyntaxElement> parse(String contract) throws IOException {
        ObjectMapper mapper = new ObjectMapper();

        JsonNode root = mapper.readTree(contract);
        return json2SolidityAST(root);
    }

    /// convert the JSON AST representation into a KeY for Solidity representation
    /// @param root the root node representing the JSON AST
    /// @return the KeY AST representation of {@code root}
    private List<SyntaxElement> json2SolidityAST(JsonNode root) {
        if ("SourceUnit".equals(root.get("nodeType").asString())) {
            return parseSourceUnit(root.get("nodes").valueStream().toList());
        }
        return new ArrayList<>();
    }

    private List<SyntaxElement> parseSourceUnit(List<JsonNode> nodes) {
        return nodes.stream()
                .filter(n -> "contract".equals(n.get("contractKind").asString()))
                .map(this::parseContract)
                .collect(Collectors.toList());
    }


    private ContractDeclaration parseContract(JsonNode contractNode) {
        String contractName = contractNode.get("canonicalName").asString(); // there is also a
        final int contractId = contractNode.get("id").asInt();
        contractIds.add(contractId);
        List<StateVariableDeclaration> fields = new ArrayList<>();
        List<FunctionDeclaration> functions = new ArrayList<>();
        List<StructDeclaration> structs = new ArrayList<>();
        List<ModifierDeclaration> modifiers = new ArrayList<>();
        List<EnumDeclaration> enums = new ArrayList<>();

        SolidityInfo info = services.getSolidityInfo();

        KeYSolidityType contractType = createPartialContractKeYSolidityType(contractName);

        assert contractType.getSolidityType() == null : "Contract has already been parsed";

        for (JsonNode node : contractNode.get("nodes").values()) {
            final String nodeType = node.get("nodeType").asString();
            switch (nodeType) {
                case "VariableDeclaration" -> fields.add(parseVariableField(contractName, node));
                case "FunctionDefinition" -> functions.add(parseFunction(node));
                case "StructDefinition" -> structs.add(parseStruct(node, contractId));
                case "ModifierDefinition" -> modifiers.add(parseModifier(node));
                case "EnumDefinition" -> enums.add(parseEnum(node));
                default -> throw new RuntimeException("Unknown node type " + nodeType);
            }
        }

        final ContractDeclaration cDecl =
            new ContractDeclaration(new Name(contractName), fields, structs, modifiers,
                functions, enums);

        contractType.setSolidityType(cDecl);

        id2Name.put(contractId, cDecl);
        completeReferences(cDecl);
        return cDecl;
    }

    private KeYSolidityType createPartialContractKeYSolidityType(String contractName) {
        Sort s = services.getNamespaces().sorts().lookup(contractName);
        if (s == null) {
            s = new SortImpl(new Name(contractName), false); // HACK, inheritance
            services.getNamespaces().sorts().addSafely(s);
        }
        KeYSolidityType contractKST = new KeYSolidityType(s);
        partialKSTMap.put(contractName, contractKST);
        return contractKST;
    }

    private void completeReferences(SyntaxElement cDecl) {
        List<SyntaxElement> elements = new ArrayList<>();
        queueRefs(cDecl, elements);
        elements.forEach(el -> {
            if (el instanceof Resolver r)
                r.resolve(id2Name);
            if (el instanceof ProgramVariable pv)
                pv.getKeYSolidityType().resolve(id2Name);
        });
    }

    private void queueRefs(SyntaxElement cDecl, List<SyntaxElement> queue) {
        IntStream.range(0, cDecl.getChildCount()).mapToObj(cDecl::getChild).forEach(child -> {
            queue.add(child);
            queueRefs(child, queue);
        });
    }


