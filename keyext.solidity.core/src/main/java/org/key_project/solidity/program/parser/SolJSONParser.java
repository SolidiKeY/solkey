    private Expression parseConditional(JsonNode initializer) {
        Expression cond = parseExpression(initializer.get("condition"));
        Expression falseExpression = parseExpression(initializer.get("falseExpression"));
        Expression trueExpression = parseExpression(initializer.get("trueExpression"));

        return new TernaryExpression(BOOL, cond, falseExpression, trueExpression);
    }

    private Expression parseIndexAccess(JsonNode initializer) {
        JsonNode baseExpression = initializer.get("baseExpression");
        Expression leftExp = baseExpression.has("referencedDeclaration")
                ? getVariableExpression(baseExpression.get("referencedDeclaration").asInt())
                : parseExpression(baseExpression);
        Expression indexExp = parseExpression(initializer.get("indexExpression"));
        return new IndexExpression(leftExp, indexExp);
    }

    /// Resolves a referenced declaration to the expression denoting a read/write of it: a
    /// [FieldReference] for a contract state variable, or the local [ProgramVariable] for a
    /// statement-local variable.
    private Expression getVariableExpression(int idLeftRef) {
        Declaration declaration = (Declaration) id2Name.get(idLeftRef);

        return switch (declaration) {
            case StateVariableDeclaration stateVarDeclaration ->
                new FieldReference(stateVarDeclaration, stateVarDeclaration.getType());
            case StatementVariableDeclaration stmVarDeclaration ->
                stmVarDeclaration.getProgramVariable();
            default -> throw new RuntimeException(
                "Declaration " + declaration + " does not denote a variable");
        };
    }

    private Expression parseMemberAccess(JsonNode initializer) {
        Expression leftExp = parseExpression(initializer.get("expression"));
        if (!initializer.has("referencedDeclaration")
                || initializer.get("referencedDeclaration").isNull()) {
            JsonNode memberNameNode = initializer.get("memberName");
            if (memberNameNode != null && !memberNameNode.isNull()) {
                FunctionDeclaration builtin = SolidityInfo
                        .getBuiltinFunctionDeclaration(new Name(memberNameNode.asString()));
                if (builtin != null && ("push".equals(memberNameNode.asString())
                        || "pop".equals(memberNameNode.asString()))) {
                    return new MemberExp(leftExp, builtin, builtin.getType());
                }
            }
            throw new RuntimeException("Unresolved member access " + initializer);
        }
        int rightId = initializer.get("referencedDeclaration").asInt();
        JsonNode expNode = initializer.get("expression");
        Type type =
            expNode.has("referencedDeclaration") ? parseReferenceTypeDeclaration(expNode) : ADDRESS;
        if (id2Name.containsKey(rightId))
            return new MemberExp(leftExp, id2Name.get(rightId), type);
        return new MemberExp(leftExp, rightId, type);
    }

    private Expression parseAssignment(JsonNode assign) {
        final String op = assign.get("operator").asString();
        Expression left = parseExpression(assign.get("leftHandSide"));
        Expression right = parseExpression(assign.get("rightHandSide"));
        return ParserUtils.parseAssignment(left, right, op);
    }

    private Expression parseUnaryOperation(JsonNode initializer) {
        Expression uExp = parseExpression(initializer.get("subExpression"));
        final String operator = initializer.get("operator").asString();
        boolean prefix = initializer.get("prefix").asBoolean();
        return ParserUtils.parseUnaryOperation(uExp, operator, prefix);
    }

    private Expression parseBinaryOperation(JsonNode initializer) {
        Expression leftExpression = parseExpression(initializer.get("leftExpression"));
        Expression rightExpression = parseExpression(initializer.get("rightExpression"));

        final String operator = initializer.get("operator").asString();
        return ParserUtils.parseBinaryOperation(leftExpression, rightExpression, operator);
    }

    private Expression parseIdentifier(JsonNode literal) {
        final int idDecl = literal.get("referencedDeclaration").asInt();
        final SyntaxElement declaration = id2Name.get(idDecl);
        Type type = parseReferenceTypeDeclaration(literal);
        return switch (declaration) {
            case StateVariableDeclaration stateVarDeclaration ->
                new FieldReference(stateVarDeclaration, type);
            case FunctionDeclaration ignored ->
                new FunctionReference(idDecl, type);
            case StatementVariableDeclaration stmVarDeclaration ->
                stmVarDeclaration.getProgramVariable();
            case EnumDeclaration enumDeclaration ->
                new EnumReference(enumDeclaration, type);
            case ProgramVariable p -> p;
            case null ->
                functionId2Type.containsKey(idDecl) ? new FunctionReference(idDecl, type)
                        : switch (type) {
                            case TupleType tupleType -> new FunctionReference(idDecl, tupleType);
                            case PrimitiveType tp -> new ContractReference(idDecl, tp);
                            default ->
                                throw new RuntimeException(
                                    "Type " + type + " is not function or contract");
                        };
            default -> throw new RuntimeException(
                "Unexpected reference declaration " + declaration + " expected a state variable.");
        };
    }

    private Literal parseLiteral(JsonNode literal) {
        final String kind = literal.get("kind").asString();
        return switch (kind) {
            case "number" -> {
                String initializerExp = literal.get("value").asString();
                yield new Uint256Literal(new BigInteger(initializerExp));
            }
            case "bool" -> {
                String initializerExp = literal.get("value").asString();
                yield initializerExp.equals("true") ? TRUE : FALSE;
            }
            // FIX!!!!
            default -> throw new RuntimeException("Not yet supported literal");
        };
    }

    private TupleType getTupleType(List<Type> types) {
        String key = types.stream().map(type -> type.name().toString())
                .collect(Collectors.joining(",", "(", ")"));
        return tupleTypes.computeIfAbsent(key, ignored -> new TupleType(types));
    }

    private @Nullable Expression findOrNullExpression(JsonNode statement, String field) {
        return statement.has(field) ? parseExpression(statement.get(field)) : null;
    }

    private KeYSolidityType getOrCreateKeYSolidityType(Type type) {
        assert (type != null && !(type instanceof KeYSolidityType));
        KeYSolidityType kst = services.getSolidityInfo().getKeYSolidityType(type);
        if (kst != null) {
            return kst;
        }
        assert !(type instanceof PrimitiveType); // Primitive types should be already present
        return switch (type) {
            // TODO need to decide how to represent tuple sorts (in particular triples etc.)
            case TupleType ignored -> throw new RuntimeException("Tuples not yet supported.");
            case DynamicArrayType dynamicArrayType ->
                getOrCreateDynamicArrayKeYSolidityType(dynamicArrayType);
            case ArrayType arrayType -> getOrCreateArrayKeYSolidityType(arrayType);
            case MappingType mappingType -> getOrCreateMappingKeYSolidityType(mappingType);
            case StructDeclaration structDecl -> {
                Sort structSort = services.getTheoryInfo().getStructLDT().targetSort();
                assert structSort != null;
                KeYSolidityType structKST = new KeYSolidityType(structDecl, structSort);
                services.getSolidityInfo().put(structKST);
                yield structKST;
            }
            case EnumDeclaration enumDecl -> {
                Sort intSort = services.getTheoryInfo().getIntLDT().targetSort();
                KeYSolidityType enumKST = new KeYSolidityType(enumDecl, intSort);
                services.getSolidityInfo().put(enumKST);
                yield enumKST;
            }
            // A contract currently being parsed: share its pending instance.
            case ContractDeclaration contractDecl -> {
                KeYSolidityType pendingKST = contractKSTs.get(contractDecl.name());
                if (pendingKST == null) {
                    throw new RuntimeException(
                        "Unknown contract type " + contractDecl.name());
                }
                yield pendingKST;
            }
            default -> throw new RuntimeException(
                "No KeYSolidityType for " + type + " (" + type.getClass().getSimpleName() + ")");
        };
    }

    private KeYSolidityType getOrCreateDynamicArrayKeYSolidityType(
            DynamicArrayType dynamicArrayType) {
        Name arrayName = dynamicArrayType.name();
        KeYSolidityType kst = dynamicArrayKSTs.get(arrayName);
        if (kst != null)
            return kst;

        Sort sort =
            new DynamicArraySort(
                getElementSort(dynamicArrayType, dynamicArrayType.getElementType()),
                valueSupersort("StValue"));
        sort = getOrAddSort(sort);
        kst = new KeYSolidityType(dynamicArrayType, sort);
        dynamicArrayKSTs.put(arrayName, kst);
        return kst;
    }

    private KeYSolidityType getOrCreateArrayKeYSolidityType(ArrayType arrayType) {
        Name arrayName = arrayType.name();
        KeYSolidityType kst = arrayKSTs.get(arrayName);
        if (kst != null)
            return kst;

        Sort sort = new ArraySort(getElementSort(arrayType, arrayType.getElementType()),
            arrayType.length(), valueSupersort("StValue"));
        sort = getOrAddSort(sort);
        kst = new KeYSolidityType(arrayType, sort);
        arrayKSTs.put(arrayName, kst);
        return kst;
    }

    private KeYSolidityType getOrCreateMappingKeYSolidityType(MappingType mappingType) {
        Name mappingName = mappingType.name();
        KeYSolidityType kst = mappingKSTs.get(mappingName);
        if (kst != null)
            return kst;

        List<KeYSolidityType> componentTypes =
            List.of(mappingType.keyType(), mappingType.valueType()).stream()
                    .map(this::getOrCreateKeYSolidityType).toList();
        if (componentTypes.stream().anyMatch(
            componentType -> componentType == null || componentType.getSort() == null)) {
            throw new RuntimeException("Mapping type " + mappingType + " contains an "
                + "unsupported component type");
        }
        Sort sort =
            new MappingSort(componentTypes.get(0).getSort(), componentTypes.get(1).getSort(),
                valueSupersort("StValue"));
        sort = getOrAddSort(sort);
        kst = new KeYSolidityType(mappingType, sort);
        mappingKSTs.put(mappingName, kst);
        return kst;
    }

    private Sort getElementSort(Type arrayType, Type elementType) {
        List<KeYSolidityType> componentTypes = List.of(elementType).stream()
                .map(this::getOrCreateKeYSolidityType).toList();
        KeYSolidityType componentType = componentTypes.getFirst();
        if (componentType == null || componentType.getSort() == null) {
            throw new RuntimeException("Array type " + arrayType + " contains an "
                + "unsupported component type");
        }
        return componentType.getSort();
    }

    private Sort getOrAddSort(Sort sort) {
        Sort existingSort = services.getNamespaces().sorts().lookup(sort.name());
        if (existingSort != null)
            return existingSort;
        services.getNamespaces().sorts().addSafely(sort);
        return sort;
    }
