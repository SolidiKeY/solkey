    private ProgramVariable parseParam(JsonNode node) {
        final int id = node.get("id").asInt();
        final String fieldName = node.get("name").asString();
        final String dataLocationS = node.get("storageLocation").asString();
        final DataLocation dataLocation = DataLocation.fromString(dataLocationS);

        ProgramVariable programVariable;
        if (node.get("typeName").has("referencedDeclaration")) {
            int typeId = node.get("typeName").get("referencedDeclaration").asInt();
            Type typeRef = (Type) id2Name.get(typeId);

            final KeYSolidityType kst = getOrCreateKeYSolidityType(typeRef);
            programVariable = new ProgramVariable(new Name(fieldName), kst, dataLocation);
        } else {
            Type type = parseTypeName(node);
            final KeYSolidityType kst = getOrCreateKeYSolidityType(type);
            programVariable = new ProgramVariable(new Name(fieldName), kst, dataLocation);
        }
        id2Name.put(id, programVariable);

        return programVariable;
    }

    private Type parseType(JsonNode node) {
        String typeName = node.get("nodeType").asString();
        return switch (typeName) {
            case "ElementaryTypeName" -> getPrimitiveType(node.get("name").asString());
            case "ArrayTypeName" -> {
                Type baseType = parseType(node.get("baseType"));
                JsonNode length = node.get("length");
                if (length == null || length.isNull())
                    yield getDynamicArrayType(baseType);
                yield getArrayType(baseType, parseArrayLength(length));
            }
            case "Mapping" ->
                getMappingType(parseType(node.get("keyType")), parseType(node.get("valueType")));
            case "UserDefinedTypeName" ->
                (Type) id2Name.get(node.get("referencedDeclaration").asInt());
            case "Identifier" -> SolidityInfo
                    .getPrimitiveType(node.get("typeDescriptions").get("typeString").asString());
            default -> throw new RuntimeException("Type " + typeName + " not covered");
        };
    }

    private @NonNull MappingType getMappingType(Type keyType, Type valueType) {
        MappingType mapping = new MappingType(keyType, valueType);
        return mappingTypes.computeIfAbsent(mapping.name(), ignored -> mapping);
    }

    private @NonNull DynamicArrayType getDynamicArrayType(Type elementType) {
        DynamicArrayType array = new DynamicArrayType(elementType);
        return dynamicArrayTypes.computeIfAbsent(array.name(), ignored -> array);
    }

    private @NonNull ArrayType getArrayType(Type elementType, int length) {
        ArrayType array = new ArrayType(elementType, length);
        return arrayTypes.computeIfAbsent(array.name(), ignored -> array);
    }

    private int parseArrayLength(JsonNode length) {
        Expression expression = parseExpression(length);
        if (expression instanceof Uint256Literal literal)
            return literal.getValue().intValueExact();
        throw new RuntimeException("Array length " + expression + " is not supported");
    }

    private StateVariableDeclaration parseVariableField(String contractName, JsonNode fieldNode) {
        final int id = fieldNode.get("id").asInt();
        final String fieldNameAsString = fieldNode.get("name").asString();
        JsonNode typeName = fieldNode.get("typeName");
        Type expType = null;
        int idRef = -1;
        if (typeName.has("referencedDeclaration")) {
            idRef = typeName.get("referencedDeclaration").asInt();
            if (id2Name.containsKey(idRef)) {
                expType = (Type) id2Name.get(idRef);
            }
        } else {
            expType = parseTypeName(fieldNode);
        }

        Visibility visibility = Visibility.fromString(fieldNode.get("visibility").asString());

        Expression initializerExp = null;
        if (fieldNode.has("value")) {
            initializerExp = parseExpression(fieldNode.get("value"));
        }

        KeYSolidityType type = getOrCreateKeYSolidityType(expType);

        ProgramVariable programVariable =
            new ProgramVariable(new Name(fieldNameAsString), type, DataLocation.Storage);

        SFunction fieldConstant =
            createFieldConstantAndRegisterField(fieldNameAsString, contractName, type);

        StateVariableDeclaration field =
            new StateVariableDeclaration(programVariable, initializerExp, visibility);
        services.getSolidityInfo().addStateVariable(field);
        id2Name.put(id, field);

        return field;
    }

    private SFunction createFieldConstantAndRegisterField(String strFieldName, String contractName,
            KeYSolidityType type) {
        // TODO should we make the unique field names parametric with the contract type as
        // parameter?
        Name fieldName = new Name(contractName + StructLDT.FIELD_SEPARATOR + strFieldName);
        SFunction fieldConstant = new SFunction(fieldName, type.getSort(), true, true);
        services.getNamespaces().functions().addSafely(fieldConstant);
        return fieldConstant;
    }

    Type parseReferenceTypeDeclaration(JsonNode expNode) {
        int id = expNode.get("referencedDeclaration").asInt();
        SyntaxElement decl = id2Name.get(id);
        return Optional.ofNullable(decl).map(v -> switch (v) {
            case Type tp -> tp;
            case FunctionDeclaration fd -> fd.getType();
            case StatementVariableDeclaration svd -> svd.getProgramVariable().getType();
            case FieldDeclaration fd -> fd.getTypeReference().referencedType;
            default -> null;
        }).orElseGet(() -> {
            if (functionId2Type.containsKey(id))
                return functionId2Type.get(id);
            else if (contractIds.contains(id))
                return ADDRESS;
            return parseType(expNode);
        });
    }

    private Expression parseExpression(JsonNode initializer) {
        final String nodeType = initializer.get("nodeType").asString();
        return switch (nodeType) {
            case "Literal" -> parseLiteral(initializer);
            case "BinaryOperation" -> parseBinaryOperation(initializer);
            case "UnaryOperation" -> parseUnaryOperation(initializer);
            case "Identifier" -> parseIdentifier(initializer);
            case "Assignment" -> parseAssignment(initializer);
            case "MemberAccess" -> parseMemberAccess(initializer);
            case "IndexAccess" -> parseIndexAccess(initializer);
            case "Conditional" -> parseConditional(initializer);
            case "TupleExpression" -> parseTuple(initializer);
            case "IndexRangeAccess" -> parseIndexRangeAccess(initializer);
            case "FunctionCall" -> parseFunctionCall(initializer);
            case "ElementaryTypeNameExpression" -> parseElementaryExpression(initializer);
            case "ExpressionStatement" -> parseExpression(initializer.get("expression"));
            case "NewExpression" -> parseNewExpression(initializer);
            default -> throw new RuntimeException("Not yet supported expression type: " + nodeType);
        };
    }

    private Expression parseNewExpression(JsonNode initializer) {
        String functionDef =
            initializer.get("typeDescriptions").get("typeString").asString();
        Type type = parseTypeName(initializer);
        return new NewExpression(functionDef, type);
    }

    private Expression parseElementaryExpression(JsonNode initializer) {
        Type type = parseTypeName(initializer);
        return new ElementaryExpression(type);
    }

    private Type parseTypeName(JsonNode initializer) {
        return parseType(initializer.get("typeName"));
    }

    private Expression parseFunctionCall(JsonNode initializer) {
        JsonNode expNode = initializer.get("expression");
        Type expType = expNode.has("referencedDeclaration") ? parseReferenceTypeDeclaration(expNode)
                : parseTypeName(expNode);
        Expression functionExp = parseExpression(expNode);
        List<Expression> arguments =
            initializer.get("arguments").valueStream().map(this::parseExpression).toList();
        return new FunctionCallExpression(expType, functionExp, arguments);
    }

    private Expression parseIndexRangeAccess(JsonNode initializer) {
        Expression baseExp = parseExpression(initializer.get("baseExpression"));
        Expression startExp = parseExpression(initializer.get("startExpression"));
        Expression endExp = parseExpression(initializer.get("endExpression"));
        return new IndexRangeExpression(baseExp, startExp, endExp, baseExp.getType());
    }

